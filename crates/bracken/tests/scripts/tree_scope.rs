/// docs-only (owner decision c8bbb2886be3, task bfc942cd7ced): a head is docs-only when every path it
/// changed since its merge base with main is a .md file or under docs/, outside crates/ and research/, and
/// is neither docs/protocol.md nor docs/design/weave-freeze.md, in any letter case: those take the full
/// table. Anything else, a rename or deletion of code included, isn't; no change at all isn't either, and
/// an unknown commit is exit 2. key leaves docs out of the tree's hash, but not those two.
#[test]
fn tree_scope_docs_only_takes_docs_but_never_the_protocol_or_the_freeze() {
    for scripts in SCRIPTS {
        let scope = repo_root().join(scripts).join("tree-scope");
        let files = [("scripts/tree-scope", scope.as_path())];
        let (_tmp, dir) = repo(&files, ".bracken/\n", |dir| {
            put(dir, "docs/protocol.md", "the protocol\n");
            put(dir, "docs/design/weave-freeze.md", "the freeze\n");
            put(dir, "src.rs", "code\n");
        });
        let main = String::from_utf8(run(&dir, "git", &["rev-parse", "main"]).stdout).unwrap().trim().to_owned();
        let head = |files: &[(&str, &str)]| plumb(&dir, &main, &[&main], files);
        let docs_only = |h: &str| {
            let out = run(&dir, "scripts/tree-scope", &["docs-only", &main, h]);
            (out.status.code(), String::from_utf8_lossy(&out.stdout).into_owned())
        };
        let key = |h: &str| String::from_utf8(run(&dir, "scripts/tree-scope", &["key", h]).stdout).unwrap();

        for files in [
            &[("README.md", "more\n")][..],
            &[("docs/notes.md", "notes\n"), ("docs/design/visualizer/css/x.css", "a {}\n")],
            &[(".claude/skills/x/SKILL.md", "a skill\n")],
        ] {
            let h = head(files);
            let (code, out) = docs_only(&h);
            assert_eq!(code, Some(0), "{scripts}: {files:?}: {out}");
            assert_eq!(key(&h), key(&main), "{scripts}: {files:?}: docs change the key");
        }
        for (path, named) in [
            ("docs/protocol.md", "docs/protocol.md"),
            ("docs/design/weave-freeze.md", "docs/design/weave-freeze.md"),
            ("Docs/Protocol.md", "Docs/Protocol.md"),
            ("research/experiment/prompts/git.md", "research/experiment/prompts/git.md"),
            ("crates/bracken/x.md", "crates/bracken/x.md"),
            ("src.rs", "src.rs"),
        ] {
            let h = head(&[("docs/notes.md", "notes\n"), (path, "changed\n")]);
            let (code, out) = docs_only(&h);
            assert_eq!(code, Some(1), "{scripts}: {path}: {out}");
            assert!(out.contains(&format!("tree-scope: not docs: {named}")), "{scripts}: {path}: {out}");
            assert_ne!(key(&h), key(&main), "{scripts}: {path}: the key leaves it out");
        }
        // Deleting code isn't docs-only.
        let (code, out) = docs_only(&head(&[("src.rs", "")]));
        assert_eq!(code, Some(1), "{scripts}: {out}");
        // No change, and an unknown commit.
        assert_eq!(docs_only(&main).0, Some(1), "{scripts}");
        assert_eq!(docs_only("no-such-commit").0, Some(2), "{scripts}");
        // The retired modes are gone.
        for mode in ["full", "packages", "light-passes"] {
            assert_eq!(
                run(&dir, "scripts/tree-scope", &[mode, "main", "main"]).status.code(),
                Some(2),
                "{scripts}: {mode}"
            );
        }
    }
}

fn lock(entries: &[(&str, &str, &str)]) -> String {
    let mut text = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n",
    );
    for (name, version, sum) in entries {
        text += &format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{sum}\"\ndependencies = [\n \"blake3\",\n]\n"
        );
    }
    text
}

/// Weave's format freeze, G6 (docs/design/weave-freeze.md 2.4, task e1d2cb38d478): tree-scope frozen names
/// every changed path under crates/tree/src/ (a new file and a rename away included), crates/tree's
/// manifest, the format guard, paths.rs, lines.rs, the fixture test and tests/fixtures/, and a Cargo.lock
/// change to the entry of a crate the formats rest on, each with its reason; an 'owner:' line for a golden
/// vector or pinned fixture value; and a 'security:' line for every path in the directories of the
/// freeze's refusals, Weave's CLI included. It exits 3, with its one line, for a head that changes none of
/// these, crates/tree's other tests and another crate's Cargo.lock entry included, and 2 on an error. A
/// changed path holding a newline or a tab is an error, named escaped, with nothing on standard output
/// (findings db2dc1c6120e, e3f9ae2b1820). full names the new paths in its list too.
#[test]
fn tree_scope_frozen_names_the_freezes_paths_each_with_what_it_needs() {
    let base_lock = lock(&[("blake3", "1.8.7", "aa"), ("serde", "1.0.0", "bb"), ("icu_casemap", "2.4.0", "cc")]);
    for scripts in SCRIPTS {
        let scope = repo_root().join(scripts).join("tree-scope");
        let files = [("scripts/tree-scope", scope.as_path())];
        let (_tmp, dir) = repo(&files, ".bracken/\n", |dir| {
            put(dir, "crates/tree/src/old.rs", "tree\n");
            put(dir, "crates/tree/src/format.rs", "format\n");
            put(dir, "Cargo.lock", &base_lock);
        });
        let git = |args: &[&str]| assert!(run(&dir, "git", args).status.success(), "git {args:?}");
        let branch = |name: &str, change: &dyn Fn()| {
            git(&["switch", "-qc", name, "main"]);
            change();
            commit_all(&dir, name);
            git(&["switch", "-q", "main"]);
        };
        let frozen = |head: &str| {
            let out = run(&dir, "scripts/tree-scope", &["frozen", "main", head]);
            (out.status.code(), String::from_utf8_lossy(&out.stdout).into_owned())
        };
        let src = "crates/tree's source, which holds Weave's frozen formats and their rules";
        let refusals = "crates/tree's source, where the freeze's refusals at write and use live";
        let cli = "Weave's CLI, where the freeze's refusals at use live";

        branch("source", &|| {
            put(&dir, "crates/tree/src/format.rs", "format, changed\n");
            put(&dir, "crates/tree/src/check/new.rs", "a new module\n");
        });
        assert_eq!(
            frozen("source"),
            (
                Some(0),
                format!(
                    "tree-scope: frozen: crates/tree/src/check/new.rs ({src})\n\
                     tree-scope: security: crates/tree/src/check/new.rs ({refusals})\n\
                     tree-scope: frozen: crates/tree/src/format.rs ({src})\n\
                     tree-scope: security: crates/tree/src/format.rs ({refusals})\n"
                )
            ),
            "{scripts}"
        );
        branch("moved", &|| git(&["mv", "crates/tree/src/old.rs", "elsewhere.rs"]));
        let (code, out) = frozen("moved");
        assert_eq!(code, Some(0), "{scripts}: {out}");
        assert!(out.contains(&format!("tree-scope: frozen: crates/tree/src/old.rs ({src})")), "{scripts}: {out}");
        assert!(out.contains("tree-scope: security: crates/tree/src/old.rs ("), "{scripts}: {out}");

        branch("guards", &|| {
            put(&dir, "crates/tree/Cargo.toml", "[package]\n");
            put(&dir, "crates/tree/tests/format_guard.rs", "// a golden vector\n");
            put(&dir, "crates/tree/tests/paths.rs", "// paths\n");
            put(&dir, "crates/tree/tests/lines.rs", "// lines\n");
            put(&dir, "crates/tree/tests/weave_fixture.rs", "// the fixture\n");
            put(&dir, "crates/tree/tests/fixtures/weave-v1/objects/ab", "bytes\n");
            put(&dir, ".config/weave-root", "ground 00\n");
        });
        assert_eq!(
            frozen("guards"),
            (
                Some(0),
                "tree-scope: frozen: .config/weave-root (the Weave Ground's committed pin: its id, and the root whose marker counts)\n\
                 tree-scope: frozen: crates/tree/Cargo.toml (crates/tree's manifest: what its formats build from)\n\
                 tree-scope: frozen: crates/tree/tests/fixtures/weave-v1/objects/ab (a Weave fixture)\n\
                 tree-scope: owner: crates/tree/tests/fixtures/weave-v1/objects/ab (a Weave fixture: the owner's own go)\n\
                 tree-scope: frozen: crates/tree/tests/format_guard.rs (the format guard: golden vectors and pins)\n\
                 tree-scope: owner: crates/tree/tests/format_guard.rs (golden vectors and pinned values: the owner's own go)\n\
                 tree-scope: frozen: crates/tree/tests/lines.rs (the ancestor rule's guard)\n\
                 tree-scope: frozen: crates/tree/tests/paths.rs (the path, folding and collision rules' guard)\n\
                 tree-scope: frozen: crates/tree/tests/weave_fixture.rs (the weave-v1 fixture's test and its pinned values)\n\
                 tree-scope: owner: crates/tree/tests/weave_fixture.rs (the weave-v1 fixture's pinned values: the owner's own go)\n"
                    .to_owned()
            ),
            "{scripts}"
        );

        branch("cli", &|| {
            put(&dir, "crates/bracken/src/weave.rs", "cli\n");
            put(&dir, "crates/bracken/src/weave/merge.rs", "cli\n");
        });
        assert_eq!(
            frozen("cli"),
            (
                Some(0),
                format!(
                    "tree-scope: security: crates/bracken/src/weave.rs ({cli})\n\
                     tree-scope: security: crates/bracken/src/weave/merge.rs ({cli})\n"
                )
            ),
            "{scripts}"
        );

        // Cargo.lock: a version, a checksum alone, an entry removed, and another crate's change.
        let lockfile = |text: String| {
            let dir = dir.as_path();
            move || put(dir, "Cargo.lock", &text)
        };
        branch(
            "bump",
            &lockfile(lock(&[("blake3", "1.9.0", "dd"), ("serde", "1.0.0", "bb"), ("icu_casemap", "2.4.0", "cc")])),
        );
        branch(
            "checksum",
            &lockfile(lock(&[("blake3", "1.8.7", "ee"), ("serde", "1.0.0", "bb"), ("icu_casemap", "2.4.0", "cc")])),
        );
        branch("dropped", &lockfile(lock(&[("blake3", "1.8.7", "aa"), ("serde", "1.0.0", "bb")])));
        branch(
            "other",
            &lockfile(lock(&[("blake3", "1.8.7", "aa"), ("serde", "1.0.1", "ff"), ("icu_casemap", "2.4.0", "cc")])),
        );
        let rests = "and Weave's frozen formats rest on it";
        let expect = [
            ("bump", format!("tree-scope: frozen: Cargo.lock (blake3 1.8.7 -> 1.9.0, {rests})\n")),
            ("checksum", format!("tree-scope: frozen: Cargo.lock (blake3 1.8.7: its entry changed, {rests})\n")),
            ("dropped", format!("tree-scope: frozen: Cargo.lock (icu_casemap 2.4.0 -> none, {rests})\n")),
        ];
        for (head, out) in expect {
            assert_eq!(frozen(head), (Some(0), out), "{scripts}: {head}");
        }

        // Nothing the freeze guards: exit 3, saying so.
        branch("elsewhere", &|| {
            put(&dir, "crates/tree/tests/merge.rs", "another test\n");
            put(&dir, "crates/bracken/src/main.rs", "the rest of the CLI\n");
            put(&dir, "crates/bracken/src/weaver.rs", "not weave.rs\n");
        });
        for head in ["other", "elsewhere"] {
            let (code, out) = frozen(head);
            assert_eq!(code, Some(3), "{scripts}: {head}: {out}");
            assert!(out.starts_with("tree-scope: nothing since ") && out.lines().count() == 1, "{scripts}: {out}");
        }
        assert_eq!(frozen("no-such-branch").0, Some(2), "{scripts}");

        // A path with a newline or a tab, frozen or not, anywhere among the changes: refused, named escaped.
        for (name, file, escaped) in [
            ("newline", "crates/tree/src/a\nb.rs", "$'crates/tree/src/a\\nb.rs'"),
            ("tab", "notes/x\ty.txt", "$'notes/x\\ty.txt'"),
        ] {
            branch(name, &|| {
                put(&dir, "crates/tree/src/format.rs", "format, changed again\n");
                put(&dir, file, "a name with a control character\n");
            });
            let out = run(&dir, "scripts/tree-scope", &["frozen", "main", name]);
            let stderr = String::from_utf8_lossy(&out.stderr);
            assert_eq!(out.status.code(), Some(2), "{scripts}: {name}: {stderr}");
            assert!(out.stdout.is_empty(), "{scripts}: {name}: {:?}", out.stdout);
            assert!(stderr.contains("control character") && stderr.contains(escaped), "{scripts}: {name}: {stderr}");
        }
        assert_eq!(run(&dir, "scripts/tree-scope", &["frozen", "main"]).status.code(), Some(2), "{scripts}");
    }
}

/// Makes a commit in `dir` with git's plumbing, through an index of its own, never the working tree: the
/// tree of `from` with `files` (path, contents) written over it, and `parents` as its parents. So a path in
/// a case a case-insensitive filesystem would fold is committed as given. A path with empty contents is
/// removed. Returns its sha.
fn plumb(dir: &Path, from: &str, parents: &[&str], files: &[(&str, &str)]) -> String {
    let entries: Vec<(&str, &str, &str)> = files.iter().map(|(p, t)| ("100644", *p, *t)).collect();
    plumb_modes(dir, from, parents, &entries)
}

/// As [`plumb`], each entry (mode, path, contents) with its mode: for 120000, a symlink, the contents are its
/// target; for 160000, a gitlink, the contents are the commit it names.
fn plumb_modes(dir: &Path, from: &str, parents: &[&str], files: &[(&str, &str, &str)]) -> String {
    let index = dir.join(format!("../index-{}", files.len() + parents.len() * 100 + from.len() * 10_000));
    let _ = std::fs::remove_file(&index);
    let git = |args: &[&str]| {
        let out = command(dir, "git", args).env("GIT_INDEX_FILE", &index).output().unwrap();
        assert!(out.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&out.stderr));
        String::from_utf8(out.stdout).unwrap().trim().to_owned()
    };
    git(&["read-tree", from]);
    let blob = dir.join("../plumb-blob");
    for (mode, path, text) in files {
        // Empty contents remove the path.
        if text.is_empty() {
            git(&["update-index", "--force-remove", path]);
            continue;
        }
        let oid = if *mode == "160000" {
            (*text).to_owned()
        } else {
            std::fs::write(&blob, text).unwrap();
            git(&["hash-object", "-w", blob.to_str().unwrap()])
        };
        git(&["update-index", "--add", "--cacheinfo", &format!("{mode},{oid},{path}")]);
    }
    let tree = git(&["write-tree"]);
    let mut args = vec!["commit-tree", tree.as_str(), "-m", "plumbed"];
    for p in parents {
        args.extend(["-p", p]);
    }
    git(&args)
}

/// Findings 89119f47ba5c and bb7107f27076. Paths are matched with ASCII case folded, since a
/// case-insensitive checkout (macOS's default) writes Crates/Tree/src/x.rs over crates/tree/src/x.rs: frozen
/// names a case variant of its paths. It refuses, exit 2 naming both, a changed path that differs only in
/// case from another path in the merged tree. With several merge bases (a criss-cross history, which a diff
/// from one can miss), it refuses, exit 2.
#[test]
fn tree_scope_folds_case_and_fails_closed_on_a_collision_or_a_criss_cross() {
    for scripts in SCRIPTS {
        let scope = repo_root().join(scripts).join("tree-scope");
        let files = [("scripts/tree-scope", scope.as_path())];
        let (_tmp, dir) = repo(&files, ".bracken/\n", |dir| {
            put(dir, "crates/tree/src/format.rs", "format\n");
            put(dir, "notes.txt", "notes\n");
        });
        let scope = |args: &[&str]| {
            let out = command(&dir, "scripts/tree-scope", args).output().unwrap();
            let said =
                (String::from_utf8_lossy(&out.stdout).into_owned(), String::from_utf8_lossy(&out.stderr).into_owned());
            (out.status.code(), said.0, said.1)
        };
        let main = String::from_utf8(run(&dir, "git", &["rev-parse", "main"]).stdout).unwrap().trim().to_owned();
        let head = |files: &[(&str, &str)]| plumb(&dir, &main, &[&main], files);

        // Case variants of each kind, none colliding with a path or directory that exists: named, as their
        // kind. (Crates/Tree/src/New.rs collides with the directory crates/: refused below.)
        let variants = head(&[
            ("crates/tree/CARGO.toml", "[package]\n"),
            ("crates/tree/tests/FIXTURES/x", "fixture\n"),
            ("crates/bracken/src/WEAVE.rs", "cli\n"),
        ]);
        let (code, out, err) = scope(&["frozen", &main, &variants]);
        assert_eq!(code, Some(0), "{scripts}: {out}{err}");
        let variants = head(&[
            ("Crates/Tree/src/New.rs", "new\n"),
            ("crates/tree/CARGO.toml", "[package]\n"),
            ("crates/tree/tests/FIXTURES/x", "fixture\n"),
            ("crates/bracken/src/WEAVE.rs", "cli\n"),
        ]);
        let (code, _, err) = scope(&["frozen", &main, &variants]);
        assert!(code == Some(2) && err.contains("Crates and crates"), "{scripts}: {err}");
        for line in [
            "tree-scope: frozen: crates/tree/CARGO.toml (",
            "tree-scope: frozen: crates/tree/tests/FIXTURES/x (",
            "tree-scope: owner: crates/tree/tests/FIXTURES/x (",
            "tree-scope: security: crates/bracken/src/WEAVE.rs (",
        ] {
            assert!(out.contains(line), "{scripts}: {line}: {out}");
        }

        // A case collision in the merged tree: refused, naming both, whether the path is frozen or not, and
        // whichever side came first.
        for (path, other) in [
            ("Crates/Tree/src/format.rs", "crates/tree/src/format.rs"),
            ("crates/tree/src/FORMAT.rs", "crates/tree/src/format.rs"),
            ("NOTES.txt", "notes.txt"),
        ] {
            let (code, out, err) = scope(&["frozen", &main, &head(&[(path, "over it\n")])]);
            assert_eq!(code, Some(2), "{scripts}: {path}: {out}{err}");
            assert!(out.is_empty(), "{scripts}: {path}: {out}");
            assert!(err.contains("differing only in case") && err.contains(path) && err.contains(other), "{err}");
        }
        // Two new paths that collide with each other.
        let (code, _, err) = scope(&["frozen", &main, &head(&[("docs/a.md", "a\n"), ("docs/A.md", "A\n")])]);
        assert!(code == Some(2) && err.contains("docs/A.md and docs/a.md"), "{scripts}: {err}");

        // A head that doesn't merge cleanly: refused.
        let tip = plumb(&dir, &main, &[&main], &[("notes.txt", "main's\n")]);
        let (code, _, err) = scope(&["frozen", &tip, &head(&[("notes.txt", "the head's\n")])]);
        assert!(code == Some(2) && err.contains("doesn't merge cleanly"), "{scripts}: {err}");

        // A criss-cross (the finding's counterexample): B2 changes a frozen file, B1 something else; the tip
        // merges B2 into B1, and the head merges them too, putting the frozen file back.
        let b2 = head(&[("crates/tree/src/f.rs", "y\n")]);
        let b1 = head(&[("notes.txt", "b1\n")]);
        let tip = plumb(&dir, &b2, &[&b1, &b2], &[("notes.txt", "b1\n")]);
        let crossed = plumb(&dir, &b1, &[&b2, &b1], &[]);
        let (code, out, err) = scope(&["frozen", &tip, &crossed]);
        assert_eq!(code, Some(2), "{scripts}: {out}{err}");
        assert!(out.is_empty() && err.contains("are all merge bases") && err.contains("criss-cross"), "{err}");
    }
}

/// Findings 5b38ef3c9557 and e1a2fe970409. APFS folds some non-ASCII letters onto ASCII ones (the long s
/// onto s, the Kelvin sign onto k), so a path holding any byte outside printable ASCII is refused by frozen,
/// exit 2 naming it escaped, frozen or not. And it reads every path
/// that differs between main's tip and the merged tree: a head's edit to a file main has since renamed into
/// crates/tree/src/ lands there through the merge's rename detection, though the head's own diff never
/// names that path.
#[test]
fn tree_scope_refuses_non_ascii_paths_and_reads_what_the_merge_changes() {
    for scripts in SCRIPTS {
        let scope = repo_root().join(scripts).join("tree-scope");
        let files = [("scripts/tree-scope", scope.as_path())];
        let body: String = (1..=40).map(|i| format!("line {i}\n")).collect();
        let (_tmp, dir) = repo(&files, ".bracken/\n", |dir| {
            put(dir, "crates/tree/src/lib.rs", "lib\n");
            put(dir, "src_old/f.rs", &body);
        });
        let scope = |args: &[&str]| {
            let out = command(&dir, "scripts/tree-scope", args).output().unwrap();
            let said =
                (String::from_utf8_lossy(&out.stdout).into_owned(), String::from_utf8_lossy(&out.stderr).into_owned());
            (out.status.code(), said.0, said.1)
        };
        let main = String::from_utf8(run(&dir, "git", &["rev-parse", "main"]).stdout).unwrap().trim().to_owned();
        let head = |files: &[(&str, &str)]| plumb(&dir, &main, &[&main], files);

        for (path, escaped) in [
            ("crates/tree/\u{17f}rc/lib.rs", "$'crates/tree/\\305\\277rc/lib.rs'"),
            ("crates/tree/tests/fixture\u{17f}/v.bin", "$'crates/tree/tests/fixture\\305\\277/v.bin'"),
            ("Cargo.loc\u{212a}", "$'Cargo.loc\\342\\204\\252'"),
            ("docs/caf\u{e9}.md", "$'docs/caf\\303\\251.md'"),
        ] {
            let h = head(&[(path, "over it\n")]);
            let (code, out, err) = scope(&["frozen", &main, &h]);
            assert_eq!(code, Some(2), "{scripts}: {path}: {out}{err}");
            assert!(out.is_empty(), "{scripts}: {path}: {out}");
            assert!(err.contains("outside printable ASCII") && err.contains(escaped), "{scripts}: {path}: {err}");
        }

        // The finding's counterexample: main renames src_old/f.rs into crates/tree/src/, and the head, from
        // before that, edits src_old/f.rs's last line. The merge puts the edit in crates/tree/src/f.rs.
        let tip = plumb(&dir, &main, &[&main], &[("src_old/f.rs", ""), ("crates/tree/src/f.rs", &body)]);
        let evil = body.replace("line 40\n", "EVIL\n");
        let edit = head(&[("src_old/f.rs", &evil)]);
        let merged = run(&dir, "git", &["merge-tree", "--write-tree", &tip, &edit]);
        assert!(merged.status.success(), "{scripts}: the merge conflicts");
        let tree = String::from_utf8(merged.stdout).unwrap().lines().next().unwrap().to_owned();
        let landed = run(&dir, "git", &["show", &format!("{tree}:crates/tree/src/f.rs")]);
        assert!(String::from_utf8_lossy(&landed.stdout).ends_with("EVIL\n"), "{scripts}: the edit didn't land");
        let (code, out, err) = scope(&["frozen", &tip, &edit]);
        assert_eq!(code, Some(0), "{scripts}: {out}{err}");
        assert!(out.contains("tree-scope: frozen: crates/tree/src/f.rs ("), "{scripts}: {out}");
        assert!(out.contains("tree-scope: security: crates/tree/src/f.rs ("), "{scripts}: {out}");
    }
}

/// Finding 304dd65b233c. main tracks no symlink and no gitlink, so a changed path that is either in the
/// merged tree or the head is refused by frozen, exit 2 naming it: a
/// symlink crates/tree/SRC would replace crates/tree/src on a case-insensitive checkout. And the case check
/// compares leading directories too: crates/TREE/x.rs and Crates/x, ordinary files, are refused, naming both
/// spellings. An ordinary head still exits 3.
#[test]
fn tree_scope_refuses_links_and_directory_case_variants() {
    for scripts in SCRIPTS {
        let scope = repo_root().join(scripts).join("tree-scope");
        let files = [("scripts/tree-scope", scope.as_path())];
        let (_tmp, dir) = repo(&files, ".bracken/\n", |dir| {
            put(dir, "crates/tree/src/lib.rs", "lib\n");
            put(dir, "notes.txt", "notes\n");
        });
        let scope = |args: &[&str]| {
            let out = command(&dir, "scripts/tree-scope", args).output().unwrap();
            let said =
                (String::from_utf8_lossy(&out.stdout).into_owned(), String::from_utf8_lossy(&out.stderr).into_owned());
            (out.status.code(), said.0, said.1)
        };
        let main = String::from_utf8(run(&dir, "git", &["rev-parse", "main"]).stdout).unwrap().trim().to_owned();
        let head = |entries: &[(&str, &str, &str)]| plumb_modes(&dir, &main, &[&main], entries);

        for (what, entry, named) in [
            ("a symlink", ("120000", "crates/tree/SRC", "../../docs/evilsrc"), "crates/tree/SRC (a symlink)"),
            ("a gitlink", ("160000", "vendor/sub", main.as_str()), "vendor/sub (a gitlink)"),
        ] {
            let h = head(&[entry]);
            let (code, out, err) = scope(&["frozen", &main, &h]);
            assert_eq!(code, Some(2), "{scripts}: {what}: {out}{err}");
            assert!(out.is_empty() && err.contains(named), "{scripts}: {what}: {err}");
        }
        for (path, both) in [("crates/TREE/x.rs", "crates/TREE and crates/tree"), ("Crates/x", "Crates and crates")] {
            let (code, out, err) = scope(&["frozen", &main, &head(&[("100644", path, "a file\n")])]);
            assert_eq!(code, Some(2), "{scripts}: {path}: {out}{err}");
            assert!(out.is_empty(), "{scripts}: {path}: {out}");
            // The changed spelling comes first.
            assert!(err.contains("differing only in case") && err.contains(both), "{scripts}: {path}: {err}");
        }
        let (code, out, err) = scope(&["frozen", &main, &head(&[("100644", "notes.txt", "more\n")])]);
        assert_eq!(code, Some(3), "{scripts}: {out}{err}");
        assert!(out.starts_with("tree-scope: nothing since "), "{scripts}: {out}");
    }
}
